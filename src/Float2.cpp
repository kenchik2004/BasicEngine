/**
 * @file   Float2.cpp
 * @brief  2次元浮動小数点ベクトル(float2)クラスの実装ファイルです。
 *         ベクトルの加減乗除、正規化、距離計算など、ゲーム開発に必要な数学処理の実体を提供します。
 */
//---------------------------------------------------------------------------
#include "float2.h"

//---------------------------------------------------------------------------------
//	コンストラクタの実装
//---------------------------------------------------------------------------------

/**
 * @brief デフォルトコンストラクタ
 *        オブジェクトが生成された際に自動で呼び出され、X座標とY座標を 0.0f で安全に初期化します。
 *        これにより、変数がメモリ内のゴミデータ（不定値）で満たされるバグを防止します。
 */
float2::float2()
{
	x = 0.0f;
	y = 0.0f;
}

/**
 * @brief 引数付きコンストラクタ
 *        指定されたx, yの座標値でベクトルを初期化します。
 *        「this->」キーワードは、クラスのメンバ変数（this->x）と関数のローカル変数（x）を
 *        明確に区別し、引数の値を確実にメンバ変数へ格納するために必要です。
 * @param x 設定するX座標（横方向成分）
 * @param y 設定するY座標（縦方向成分）
 */
float2::float2( float x, float y )
{
	this->x = x;
	this->y = y;
}

//---------------------------------------------------------------------------------
//	値のクリア処理
//---------------------------------------------------------------------------------

/**
 * @brief 各成分を0にするクリア処理
 *        座標や速度を原点、または静止状態にリセットしたい時に使用します。
 */
void float2::clear()
{
	x = 0.0f;
	y = 0.0f;
}

//---------------------------------------------------------------------------------
//	値の設定（セット）処理
//---------------------------------------------------------------------------------

/**
 * @brief 2つの数値を直接指定して、ベクトルのx, yを再設定します。
 * @param x 新しいX座標成分
 * @param y 新しいY座標成分
 */
void float2::set( float x, float y )
{
	this->x = x;
	this->y = y;
}

/**
 * @brief 他の float2 ベクトルオブジェクトの値をコピーして、自身の x, y に設定します。
 * @param v コピー元となる別の float2 ベクトルへの参照
 */
void float2::set( float2 &v )
{
	x = v.x;
	y = v.y;
}

//---------------------------------------------------------------------------------
//	ベクトルの長さ（大きさ）の算出
//---------------------------------------------------------------------------------

/**
 * @brief ベクトルの現在の長さ（大きさ）を計算して返します。
 *        直角三角形の斜辺の長さを求める「三平方の定理（ピタゴラスの定理）」である
 *        x^2 + y^2 = (長さ)^2 から導き出します。
 *        C言語標準関数の「sqrtf」（平方根＝ルートの計算）を使用しています。
 * @return 算出されたベクトルの長さ（float型）
 */
float float2::GetLength()
{
	// Xの2乗とYの2乗を足し合わせ、その平方根（ルート）をとることで長さを計算します。
	return sqrtf( x * x + y * y );
}

//---------------------------------------------------------------------------------
//	ベクトルの正規化（長さを1にする処理）
//---------------------------------------------------------------------------------

/**
 * @brief 自身のベクトルの向き（角度）を保ったまま、長さを「1」に変換（正規化）します。
 *        各成分を全体の長さで割る（x / 長さ, y / 長さ）ことで、ベクトルのスケールを 1.0f にします。
 *        ※長さが0のベクトルを割ろうとすると「ゼロ除算（0で割る重大なエラー）」が発生するため、
 *          事前に長さが0より大きいことを確認（length > 0.0f）して安全にガードしています。
 */
void float2::normalize()
{
	// 現在のベクトルの長さを求めます
	float length = GetLength();
	
	// 長さが0より大きい場合のみ、割る処理を行います（安全対策）
	if( length > 0.0f ){
		// 各成分を長さで割ることで、ベクトルの全体の長さをちょうど1.0fにします
		x = x / length;
		y = y / length;
	}
}

/**
 * @brief 自身は書き換えずに、正規化された新しいベクトルを作成して返します。
 *        「一時的な方向ベクトル」を求めたいが、自身の座標や速度は変えたくない時に適しています。
 * @return 向きは同じで長さが「1」になった新しい float2 オブジェクト
 */
float2 float2::normalized()
{
	// 自身のコピーを作成します
	float2 vec = *this;
	// コピーしたベクトルに対して正規化処理を適用します
	vec.normalize();
	// 正規化したコピーを返します（元の自分は変更されません）
	return vec;
}

//---------------------------------------------------------------------------------
//	長さの設定
//---------------------------------------------------------------------------------

/**
 * @brief ベクトルの向きを保ったまま、長さを任意の値に強制設定します。
 *        一度長さを1に正規化した後、指定された長さ（倍率）を各成分に掛け合わせます。
 * @param length 設定したい新しい長さ（float型）
 */
void float2::SetLength( float length )
{
	// まずは一度ベクトルの長さを1（方向のみの状態）にします
	normalize();
	// 方向に対して目標の長さを掛け算することで、任意の大きさに調整します
	x = x * length;
	y = y * length;
}

//---------------------------------------------------------------------------------
//	演算子のオーバーロード（operator）
//---------------------------------------------------------------------------------

/**
 * @brief 代入演算子（=）
 *        右辺にある float2 の値を、左辺（自分自身）の各成分に完全に上書きコピーします。
 * @param v コピー元となる別の float2 ベクトル
 * @return 自身（*this）への参照
 */
float2& float2::operator = ( const float2 &v )
{
	x = v.x;
	y = v.y; 
	return *this; 
}

/**
 * @brief 加算代入演算子（+=）
 *        自身の x, y 座標に、別のベクトル v の x, y を足し込んで上書きします。
 *        例えば、現在の座標に移動速度ベクトルを加える（移動させる）際によく使われます。
 * @param v 加算したい別の float2 ベクトル
 * @return 加算処理が行われた自身への参照
 */
float2& float2::operator += ( const float2 &v )
{
	x += v.x;
	y += v.y;
	return *this;
}

/**
 * @brief 減算代入演算子（-=）
 *        自身の x, y 座標から、別のベクトル v の x, y を引き算して上書きします。
 * @param v 減算したい別の float2 ベクトル
 * @return 減算処理が行われた自身への参照
 */
float2& float2::operator -= ( const float2 &v )
{
	x -= v.x;
	y -= v.y;
	return *this;
}

/**
 * @brief 乗算代入演算子（*=）
 *        ベクトルの各成分に、指定された実数（スカラー値）を掛け合わせます。
 *        ベクトルの向きはそのままで、大きさを f倍（スピードアップなど）にするときに使用します。
 * @param f 掛け算する実数の倍率（スカラー）
 * @return 乗算処理が行われた自身への参照
 */
float2& float2::operator *= ( const float f )
{
	x *= f;
	y *= f;
	return *this;
}

/**
 * @brief 除算代入演算子（/=）
 *        ベクトルの各成分を、指定された実数（スカラー値）で割り算します。
 *        ベクトルの大きさを f分の1 に縮小するときに用います。※0での除算には注意が必要です。
 * @param f 割り算する実数のスカラー値
 * @return 除算処理が行われた自身への参照
 */
float2& float2::operator /= ( const float f )
{
	x /= f;
	y /= f;
	return *this;
}

//---------------------------------------------------------------------------------
//	二項演算子の実装（非メンバ関数）
//---------------------------------------------------------------------------------

/**
 * @brief 2つのベクトルの加算（+）
 *        2つのベクトルのそれぞれの成分を足し合わせた、新しい float2 ベクトルを返します。
 * @param v1 1つ目のベクトル
 * @param v2 2つ目のベクトル
 * @return 加算結果の新しいベクトル
 */
float2 operator + ( const float2 &v1, const float2 &v2 )
{
	float2 v;
	v.x = v1.x + v2.x;
	v.y = v1.y + v2.y;
	return v;
}

/**
 * @brief 2つのベクトルの減算（-）
 *        2つのベクトルのそれぞれの成分を引き算した、新しい float2 ベクトルを返します。
 *        ゲーム内では「標的オブジェクト(v1)から、自分のオブジェクト(v2)への方向」を求める際などに重宝します。
 * @param v1 1つ目のベクトル
 * @param v2 2つ目のベクトル
 * @return 減算結果の新しいベクトル
 */
float2 operator - ( const float2 &v1, const float2 &v2 )
{
	float2 v;
	v.x = v1.x - v2.x;
	v.y = v1.y - v2.y;
	return v;
}

/**
 * @brief ベクトルと実数の乗算（*）
 *        指定されたベクトルの各成分に実数（スカラー値）を掛け合わせた、新しい float2 ベクトルを返します。
 * @param v 対象のベクトル
 * @param f スカラー倍率
 * @return 乗算結果の新しいベクトル
 */
float2 operator * ( const float2 &v, const float f )
{
	float2 r;
	r.x = v.x * f;
	r.y = v.y * f;
	return r;
}

/**
 * @brief ベクトルと実数の除算（/）
 *        指定されたベクトルの各成分を実数（スカラー値）で割った、新しい float2 ベクトルを返します。
 * @param v 対象のベクトル
 * @param f 割るスカラー値
 * @return 除算結果の新しいベクトル
 */
float2 operator / ( const float2 &v, const float f )
{
	float2 r;
	r.x = v.x / f;
	r.y = v.y / f;
	return r;
}

//---------------------------------------------------------------------------------
//	便利なユーティリティ関数の実装
//---------------------------------------------------------------------------------

/**
 * @brief 2つの座標位置（pos1, pos2）の間の直線距離を算出します。
 *        2点間の差分（pos1 - pos2）をとることで、片方からもう片方への「差分ベクトル」を求め、
 *        そのベクトルの長さ（GetLength）を取得することで距離を計算します。
 * @param pos1 1つ目の位置座標
 * @param pos2 2つ目の位置座標
 * @return 2点間の直線距離（float型）
 */
float GetFloat2Distance( float2 &pos1, float2 &pos2 )
{
	// 2点間の位置差分を表すベクトルを作ります
	float2 v = pos1 - pos2;
	// 差分ベクトルの長さを測定して返します
	return v.GetLength();
}

/**
 * @brief 2つのベクトルの内積（ドット積）を算出します。
 *        計算式：v1.x * v2.x + v1.y * v2.y
 *        内積は以下の用途に便利です：
 *        - 結果が「正」の場合：2つのベクトルの向きが同じ方向（鋭角：90度未満）を向いている
 *        - 結果が「負」の場合：逆方向（鈍角：90度超）を向いている
 *        - 結果が「0」の場合：2つのベクトルが完全に直交（90度）している
 * @param v1 1つ目のベクトル
 * @param v2 2つ目のベクトル
 * @return 内積値（float型、角度の余弦（cosθ）に比例するスカラー値）
 */
float GetFloat2Dot( float2 &v1, float2 &v2 )
{
	return v1.x * v2.x + v1.y * v2.y;
}

/**
 * @brief 2つのベクトルの外積（クロス積）のZ成分値を算出します。
 *        計算式：v1.x * v2.y - v1.y * v2.x
 *        外積は、2次元空間において以下の用途で強力な効果を発揮します：
 *        - 結果が「正」の場合：v1から見てv2が反時計回り（左側）に位置する
 *        - 結果が「負」の場合：v1から見てv2が時計回り（右側）に位置する
 *        - 結果が「0」の場合：2つのベクトルが同一線上（並行）にある
 *        （キャラクターの視線に対して敵が右にいるか左にいるかの判定などに頻出します）
 * @param v1 1つ目のベクトル
 * @param v2 2つ目のベクトル
 * @return 外積値（float型）
 */
float GetFloat2Cross( float2 &v1, float2 &v2 )
{
	return v1.x * v2.y - v1.y * v2.x;
}
